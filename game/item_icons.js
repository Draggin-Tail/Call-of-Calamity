  const G = () => window.GAME_DATA;
  function tier(id) { const it = G().gear[id]; if (!it) return 1; if (it.unique) return 0; const T = G().gearTiers; return (T && T.tierOfItem && T.tierOfItem(id)) || it.tier || 1; }
  const ACC = [[/boots|compass/, 'boots'], [/ring|band|circlet/, 'ring'], [/badge|seal|coin|token|tally|key|tooth/, 'coin'], [/bell|horn|hearthstone/, 'star']];
  function pic(id) {
    const it = G().gear[id] || {};
    if (it.weapon) return ({ sword: 'sword', katana: 'sword', dagger: 'dagger', greatsword: 'greatsword', mace: 'mace', maul: 'mace', spear: 'spear', polearm: 'spear', javelin: 'spear', bow: 'bow', crossbow: 'crossbow', handxbow: 'crossbow', staff: 'staff', wand: 'wand', fist: 'fist', instrument: 'lute' })[it.weapon.family] || 'sword';
    if (it.slot === 'OffHand') return it.offType === 'book' ? 'book' : it.offType === 'relic' ? 'star' : 'shield';
    if (it.slot === 'Head') return it.weight === 'light' ? 'hood' : 'helm';
    if (it.slot === 'Body') return it.weight === 'light' ? 'robe' : 'mail';
    if (it.slot === 'Accessory') { for (const [re, p] of ACC) if (re.test(id)) return p; return 'charm'; }
    return 'star';
  }
  const cache = {};
  function draw(name, t, s) {
    const key = name + '|' + t + '|' + s; if (cache[key] !== undefined) return cache[key];
    const rows = MAPS[name].trim().split('\n'), m = METAL[t || 3], c = CLOTH[t || 3];
    const P = { k: '#151a20', w: '#ffffff', b: m[2], m: m[1], d: m[0], h: '#8a5a2c', H: '#5a3618', g: '#e2b24c', G: '#9b6f22', r: '#c0453a', R: '#9a3029', c: c[1], C: c[0], j: '#5fd0e0' };
    let url = '';
    try {
      const cv = document.createElement('canvas'); cv.width = cv.height = 16 * s; const g = cv.getContext('2d');
      rows.forEach((row, y) => { for (let x = 0; x < 16 && x < row.length; x++) { const ch = row[x]; if (ch !== '.' && P[ch]) { g.fillStyle = P[ch]; g.fillRect(x * s, y * s, s, s); } } });
      url = cv.toDataURL();
    } catch (e) { url = ''; }   // a browser that refuses canvas export shows the slot without a picture
    return (cache[key] = url);
  }
